def seed():
    """Берём литералы из исходного проекта, не выполняя его код."""
    tasks, sheets, old = [], [], {}
    source = Path(__file__).resolve().parent.parent / "database.py"
    if source.exists():
        for node in ast.walk(ast.parse(source.read_text(encoding="utf-8"))):
            if isinstance(node, ast.Assign):
                for target in node.targets:
                    if isinstance(target, ast.Name) and target.id in ("tasks", "cheat_sheets"):
                        old[target.id] = ast.literal_eval(node.value)
    for tid, exam, topic, question, answer, hint in old.get("tasks", []):
        tasks.append(dict(id="math-"+str(tid), exam=exam, subject="Математика", grade=9 if exam=="ОГЭ" else 11,
                          topic=topic, question=question, answers=[answer], hint=hint, explanation=hint, source="Учебный набор"))
    for exam, topic, description in old.get("cheat_sheets", []):
        sheets.append(dict(exam=exam, subject="Математика", grade=9 if exam=="ОГЭ" else 11, topic=topic, description=description))
    for exam, subjects in EXAMS.items():
        for subject in subjects:
            if subject not in EXAMPLES:
                continue
            topic, question, answer, hint = EXAMPLES[subject]
            tasks.append(dict(id=exam+"-"+subject, exam=exam, subject=subject, grade=9 if exam=="ОГЭ" else 11,
                topic=topic, question=question, answers=[answer], hint=hint, explanation=hint, source="Демонстрационный пример"))
            sheets.append(dict(exam=exam, subject=subject, grade=9 if exam=="ОГЭ" else 11, topic=topic, description=hint))
    return tasks, sheets
